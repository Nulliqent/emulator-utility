// Generates src/sdk-registry.gen.ts and the dependency list in package.json from service-map.tsv
import fs from "node:fs";
const rows = fs.readFileSync(new URL("./service-map.tsv", import.meta.url), "utf8").trim().split("\n").map(l => l.split("\t"));
const SDK = process.argv[2] ?? "3.1171.0";
let out = "// GENERATED by scripts/gen.mjs. Do not edit.\nexport const registry: Record<string, () => Promise<unknown>> = {\n";
for (const [crate, , pkg] of rows) out += `  ${JSON.stringify(crate)}: () => import(${JSON.stringify(pkg)}),\n`;
out += "};\n";
fs.writeFileSync(new URL("../src/sdk-registry.gen.ts", import.meta.url), out);
const pj = JSON.parse(fs.readFileSync(new URL("../package.json", import.meta.url), "utf8"));
pj.dependencies = Object.fromEntries(rows.map(r => [r[2], SDK]).sort());
fs.writeFileSync(new URL("../package.json", import.meta.url), JSON.stringify(pj, null, 2) + "\n");
console.log(rows.length, "services");
