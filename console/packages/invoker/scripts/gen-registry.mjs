// Generates src/sdk-registry.gen.js (plus a fixed .d.ts, so tsc never follows the 436 imports) and the SDK client
// dependencies in package.json from the committed Catalog index (dist/catalog/index.json).
// Usage: node scripts/gen-registry.mjs [sdkVersion]   (pinned: spike #3 measured 3.1171.0)
import fs from "node:fs";

const SDK = process.argv[2] ?? "3.1171.0";
const here = (p) => new URL(p, import.meta.url);
const index = JSON.parse(fs.readFileSync(here("../../../dist/catalog/index.json"), "utf8"));
const rows = index.entries.map((e) => [e.serviceId, e.sdkPackage]).sort((a, b) => a[0].localeCompare(b[0]));

let out = "// GENERATED by scripts/gen-registry.mjs from dist/catalog/index.json. Do not edit.\n";
out += "// One lazy import per Service, so Vite emits one chunk each and nothing loads until a Service is used.\n";
out += "export const registry = {\n";
for (const [id, pkg] of rows) out += `  ${JSON.stringify(id)}: () => import(${JSON.stringify(pkg)}),\n`;
out += "};\n";
fs.writeFileSync(here("../src/sdk-registry.gen.js"), out);
fs.writeFileSync(
  here("../src/sdk-registry.gen.d.ts"),
  "// Fixed declaration for the generated registry: tsc never follows its 436 imports.\nexport const registry: Record<string, () => Promise<Record<string, unknown>>>;\n",
);

const pjUrl = here("../package.json");
const pj = JSON.parse(fs.readFileSync(pjUrl, "utf8"));
// Merge: keep every dependency that is not an SDK client, replace the SDK clients.
const kept = Object.entries(pj.dependencies ?? {}).filter(([k]) => !k.startsWith("@aws-sdk/client-"));
const clients = [...new Set(rows.map((r) => r[1]))].map((p) => [p, SDK]);
pj.dependencies = Object.fromEntries([...kept, ...clients].sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(pjUrl, JSON.stringify(pj, null, 2) + "\n");
console.log(rows.length, "services");
